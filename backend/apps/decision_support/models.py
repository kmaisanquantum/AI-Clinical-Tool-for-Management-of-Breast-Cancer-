from django.conf import settings
from django.db import models
from django.utils import timezone


class Guideline(models.Model):
    """Clinical guideline definition (e.g. PNG Breast Cancer Management Guideline)."""
    code = models.CharField(max_length=100, unique=True)
    title = models.CharField(max_length=255)
    description = models.TextField(blank=True)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    def __str__(self):
        return f"{self.code} - {self.title}"


class GuidelineVersion(models.Model):
    """Specific versioned release of a clinical guideline."""
    guideline = models.ForeignKey(
        Guideline,
        on_delete=models.CASCADE,
        related_name="versions",
    )
    version_number = models.CharField(max_length=50)
    source_citation = models.TextField(help_text="Bibliographic or formal guideline source citation.")
    approved_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="approved_guideline_versions",
    )
    approved_at = models.DateTimeField(null=True, blank=True)
    is_active = models.BooleanField(default=True)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        unique_together = ("guideline", "version_number")

    def __str__(self):
        return f"{self.guideline.code} v{self.version_number}"


class DecisionRule(models.Model):
    """Individual decision rule under a guideline version."""
    guideline_version = models.ForeignKey(
        GuidelineVersion,
        on_delete=models.CASCADE,
        related_name="decision_rules",
    )
    rule_code = models.CharField(max_length=100)
    name = models.CharField(max_length=255)
    description = models.TextField(blank=True)

    class Meta:
        unique_together = ("guideline_version", "rule_code")

    def __str__(self):
        return f"{self.rule_code}: {self.name}"


class RuleVersion(models.Model):
    """Versioned implementation of a decision rule."""
    STATUS_CHOICES = (
        ("active", "Active"),
        ("draft", "Draft"),
        ("deprecated", "Deprecated"),
    )

    decision_rule = models.ForeignKey(
        DecisionRule,
        on_delete=models.CASCADE,
        related_name="versions",
    )
    version_number = models.CharField(max_length=50)
    logic_spec = models.JSONField(
        default=dict,
        help_text="JSON representation of rule conditions, threshold parameters, and triage actions.",
    )
    source_citation = models.TextField(help_text="Citation or literature basis for this rule version.")
    approved_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="approved_rule_versions",
    )
    approved_at = models.DateTimeField(null=True, blank=True)
    status = models.CharField(max_length=30, choices=STATUS_CHOICES, default="active")
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        unique_together = ("decision_rule", "version_number")

    def __str__(self):
        return f"{self.decision_rule.rule_code} v{self.version_number} ({self.status})"


class DecisionSupportAssessment(models.Model):
    """Triage assessment generated by rule evaluation against clinical encounter data."""
    TRIAGE_URGENT = "URGENT"
    TRIAGE_PRIORITY = "PRIORITY"
    TRIAGE_ROUTINE = "ROUTINE"

    TRIAGE_CHOICES = (
        (TRIAGE_URGENT, "Urgent Triage"),
        (TRIAGE_PRIORITY, "Priority Triage"),
        (TRIAGE_ROUTINE, "Routine Triage"),
    )

    encounter = models.ForeignKey(
        "clinical.Encounter",
        on_delete=models.CASCADE,
        related_name="decision_assessments",
    )
    rule_versions_applied = models.ManyToManyField(
        RuleVersion,
        blank=True,
        related_name="assessments",
    )
    triage_level = models.CharField(max_length=20, choices=TRIAGE_CHOICES)
    summary_recommendation = models.TextField()
    reasoning_payload = models.JSONField(
        default=dict,
        help_text="Detailed payload outlining matched criteria, input values, and rule triggers.",
    )
    calculated_at = models.DateTimeField(default=timezone.now)

    def __str__(self):
        return f"DecisionAssessment(Encounter {self.encounter_id} - Triage: {self.triage_level})"


class ClinicianReview(models.Model):
    """Human clinician review and override/confirmation of decision support assessment."""
    assessment = models.ForeignKey(
        DecisionSupportAssessment,
        on_delete=models.CASCADE,
        related_name="clinician_reviews",
    )
    reviewer = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name="clinician_reviews",
    )
    agree_with_recommendation = models.BooleanField()
    clinician_action_taken = models.TextField(blank=True)
    notes = models.TextField(blank=True)
    reviewed_at = models.DateTimeField(default=timezone.now)

    def __str__(self):
        status_str = "Agreed" if self.agree_with_recommendation else "Disagreed"
        return f"Review({self.reviewer} - {status_str} with Assessment {self.assessment_id})"
